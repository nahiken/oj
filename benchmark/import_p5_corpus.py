"""Emit (or clean) the SQL that loads the P5 corpus into `problem`.

    python benchmark/import_p5_corpus.py                # write .runtime/tmp/p5-import.sql
    python benchmark/import_p5_corpus.py --cleanup      # write the delete-only SQL

The SQL is written with hex literals (`CONVERT(0x.. USING utf8mb4)`) because the
repo path and the payload both contain non-ASCII text, and passing that through
`mysql.exe -e` gets mangled by the Windows console code page.

Rows are keyed by a fixed id (910001+ for English, 920001+ for Chinese) and use
`ON DUPLICATE KEY UPDATE`, so re-running converges instead of duplicating. Rows
whose id disappeared from a fixture are deleted, so the table always matches the
fixtures exactly.
"""
import argparse
import json
import os
import sys

EN_PATH = os.path.join("benchmark", "fixtures", "p5-corpus.en.json")
ZH_PATH = os.path.join("benchmark", "fixtures", "p5-corpus.zh.json")
OUT_SQL = os.path.join(".runtime", "tmp", "p5-import.sql")

COLUMNS = (
    "id, title, content, difficulty, tags, answer, submit_num, accepted_num, "
    "judge_case, judge_config, thumb_num, favour_num, user_id, create_time, "
    "update_time, is_delete, lang, source"
)
UPDATE = ", ".join("%s=VALUES(%s)" % (c, c) for c in COLUMNS.split(", ")[1:])


def lit(text):
    return "CONVERT(0x%s USING utf8mb4)" % str(text).encode("utf-8").hex()


def load():
    rows = []
    for path in (EN_PATH, ZH_PATH):
        with open(path, encoding="utf-8") as fh:
            for item in json.load(fh):
                rows.append(
                    {
                        "id": item["id"],
                        "title": item["title"],
                        "content": item["content"],
                        "difficulty": item["difficulty"],
                        "tags": json.dumps(item["tags"], ensure_ascii=False, separators=(",", ":")),
                        "lang": item["lang"],
                        "source": item["source"],
                    }
                )
    return rows


def values(row):
    return "(%d, %s, %s, %s, %s, NULL, 0, 0, NULL, NULL, 0, 0, 1, NOW(3), NOW(3), 0, %s, %s)" % (
        row["id"],
        lit(row["title"]),
        lit(row["content"]),
        lit(row["difficulty"]),
        lit(row["tags"]),
        lit(row["lang"]),
        lit(row["source"]),
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cleanup", action="store_true")
    args = parser.parse_args()

    os.makedirs(os.path.dirname(OUT_SQL), exist_ok=True)
    if args.cleanup:
        with open(OUT_SQL, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("DELETE FROM problem WHERE source = 'imported';\n")
        print("wrote %s (cleanup)" % OUT_SQL)
        return 0

    rows = load()
    ids = ",".join(str(r["id"]) for r in rows)
    with open(OUT_SQL, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("-- generated by benchmark/import_p5_corpus.py - do not edit\n")
        fh.write("START TRANSACTION;\n")
        for row in rows:
            fh.write(
                "INSERT INTO problem (%s) VALUES %s ON DUPLICATE KEY UPDATE %s;\n"
                % (COLUMNS, values(row), UPDATE)
            )
        fh.write("DELETE FROM problem WHERE source = 'imported' AND id NOT IN (%s);\n" % ids)
        fh.write("COMMIT;\n")
    en = sum(1 for r in rows if r["lang"] == "en")
    zh = sum(1 for r in rows if r["lang"] == "zh")
    print("wrote %s: %d rows (en=%d zh=%d)" % (OUT_SQL, len(rows), en, zh))
    return 0


if __name__ == "__main__":
    sys.exit(main())
